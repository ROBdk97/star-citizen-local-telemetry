using System.Text;
using StarCitizen.LocalTelemetry;

namespace GameActionsGenerator;

/// <summary>Renders the <c>GameActions.cs</c> catalog from a list of actions.</summary>
public static class GameActionsWriter
{
    private static readonly Dictionary<string, string> NameOverrides = new(StringComparer.Ordinal)
    {
        ["v_flightready"] = "FlightReady"
    };

    public static string Render(IEnumerable<GameAction> actions, string gameVersion)
    {
        var categories = actions
            .DistinctBy(a => a.Name)
            .GroupBy(a => a.Category)
            .OrderBy(g => g.Key, StringComparer.Ordinal)
            .Select(g => (Class: ToPascalCase(g.Key), g.Key, Actions: Members(g.Key, g)))
            .ToList();

        var classNames = new HashSet<string>(StringComparer.Ordinal);
        foreach (var category in categories)
        {
            if (!classNames.Add(category.Class))
                throw new InvalidOperationException($"Categories produce the same class name '{category.Class}'.");
        }

        var sb = new StringBuilder();
        sb.Append($"// Action names advertised by StarCitizen.exe {gameVersion} (PTU) via ListTriggerableActions.\n");
        sb.Append("// Other game versions may add or remove actions; use StarCitizenTelemetryClient.GetActionsAsync to discover them at runtime.\n");
        sb.Append("// Generated by tools/Update-Actions.ps1; do not edit by hand.\n\n");
        sb.Append("namespace StarCitizen.LocalTelemetry;\n\n");
        sb.Append("/// <summary>Known triggerable action names, grouped by the category the game reports.</summary>\n");
        sb.Append("public static class GameActions\n{\n");
        foreach (var category in categories)
        {
            sb.Append($"    /// <summary>Actions in the <c>{category.Key}</c> category.</summary>\n");
            sb.Append($"    public static class {category.Class}\n    {{\n");
            sb.Append("        /// <summary>The category name the game reports.</summary>\n");
            sb.Append($"        public const string Category = \"{category.Key}\";\n");
            foreach (var (member, action) in category.Actions)
            {
                var holdable = action.Holdable ? " Holdable." : "";
                sb.Append($"        /// <summary>The <c>{action.Name}</c> action.{holdable}</summary>\n");
                sb.Append($"        public const string {member} = \"{action.Name}\";\n");
            }
            sb.Append("    }\n\n");
        }

        sb.Append("    /// <summary>The full catalog known at the time this library was built.</summary>\n");
        sb.Append("    public static IReadOnlyList<GameAction> Known { get; } =\n    [\n");
        foreach (var category in categories)
        {
            foreach (var (member, action) in category.Actions)
            {
                var holdable = action.Holdable ? "true" : "false";
                sb.Append($"        new({category.Class}.{member}, {category.Class}.Category, {holdable}),\n");
            }
        }

        sb.Append("    ];\n}\n");
        return sb.ToString();
    }

    private static List<(string Member, GameAction Action)> Members(string category, IEnumerable<GameAction> actions)
    {
        var used = new HashSet<string>(StringComparer.Ordinal) { "Category" };
        var members = new List<(string, GameAction)>();
        foreach (var action in actions.OrderBy(a => a.Name, StringComparer.Ordinal))
        {
            var baseName = MemberName(category, action.Name);
            var name = baseName;
            for (var i = 2; !used.Add(name); i++) name = baseName + i;
            members.Add((name, action));
        }

        return members;
    }

    internal static string MemberName(string category, string actionName)
    {
        if (NameOverrides.TryGetValue(actionName, out var overridden)) return overridden;
        var name = actionName;
        if (name.StartsWith("v_", StringComparison.Ordinal)) name = name[2..];
        if (category == "player_emotes" && name.StartsWith("emote_", StringComparison.Ordinal)) name = name[6..];
        return ToPascalCase(name);
    }

    internal static string ToPascalCase(string value)
    {
        var sb = new StringBuilder();
        foreach (var part in value.Split(['_', '-', '.', ' '], StringSplitOptions.RemoveEmptyEntries))
        {
            var clean = new string([.. part.Where(char.IsLetterOrDigit)]);
            if (clean.Length > 0) sb.Append(char.ToUpperInvariant(clean[0])).Append(clean[1..]);
        }

        if (sb.Length == 0) return "_";
        return char.IsDigit(sb[0]) ? "_" + sb : sb.ToString();
    }
}
